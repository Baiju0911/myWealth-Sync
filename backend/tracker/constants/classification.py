    @classmethod
    def get_all_system_blacklist(cls) -> Set[str]:
        combined = (
            cls.RULE_SAFETY_BLACKLIST
            | cls.NOISE_KEYWORDS
            | cls.CATASTROPHIC_KEYWORDS
            | cls.UPI_RAIL_TOKENS
            | cls.CORPORATE_NOISE_SUFFIXES
        )
        return combined - cls.OK_WORD_LIST
